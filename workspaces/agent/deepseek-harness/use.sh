#!/usr/bin/env bash
# Point the harness at one of the models this cluster serves.
#
# dsh reads ONE file - $DSH_HOME/settings.yaml, which compose.yml mounts from
# ./dsh-home. So "switching model" means putting a different file there. That
# is all this script does, plus the one check that is worth doing: ASK THE
# SERVER whether the id in the file is a name it actually answers to.
#
# That check exists because the documented failure here is silent. `models[].id`
# must be the SERVED name (`--served-model-name`), not the HF repo id, and a
# wrong one does not fail at startup - the UI simply returns an error on the
# first message, long after you have stopped thinking about settings.
#
#   ./use.sh                        list what is available, and what is active
#   ./use.sh <workspace>            use the settings shipped for that workspace
#   ./use.sh --port 8891 [--id X]   build one from a RUNNING server instead
#   ./use.sh --port 8903 --host H   ...from a server on another node
#
# The --port form is for the three llama.cpp workspaces, which pass no --alias:
# their id is whatever llama.cpp derived from the GGUF, so this repo cannot
# ship it honestly and asks the server instead.
#
# WHERE THE HARNESS RUNS. This script writes the file dsh reads, wherever that
# is: HARNESS_HOST in .env names the ssh target (default gb10-homer), and the
# endpoint line is rewritten to THAT node's view of the server. `local` keeps
# everything on this machine. See README, "Where the harness runs".
set -euo pipefail

cd "$(dirname "$(readlink -f "$0")")"

[[ -f .env ]] && { set -a; # shellcheck disable=SC1091
                   source .env; set +a; }

DEFAULT=vllm-2node-qwen38-flash-next
HARNESS_HOST=${HARNESS_HOST:-gb10-homer}
REMOTE_DIR=${REMOTE_DIR:-ws-deepseek-harness}
LIVE=dsh-home/settings.yaml

c_bold=$'\033[1m'; c_dim=$'\033[2m'; c_grn=$'\033[32m'; c_yel=$'\033[33m'; c_off=$'\033[0m'
[[ -t 1 ]] || { c_bold=; c_dim=; c_grn=; c_yel=; c_off=; }

die() { echo "use.sh: $*" >&2; exit 1; }

# A read loop rather than `sed 's/^/  /'` - same output, and shellcheck's
# SC2001 is a `make check` failure in this repo, not a suggestion.
indent() { local pad=$1 line; while IFS= read -r line; do printf '%s%s\n' "$pad" "$line"; done; }

available() { local f; for f in settings/*.yaml; do basename "$f" .yaml; done; }

# The endpoint and id a settings file declares. Deliberately grep and not a
# YAML parser: these files are generated by this workspace in one fixed shape,
# and adding a python dependency to a script whose whole job is `cp` is not a
# trade worth making.
#
# The host is NOT assumed to be loopback. The harness runs on gb10-homer and
# reaches the server on odysseus over the mesh, so a settings file may name any
# host - and the deploy rewrites this one line to that node's view.
field_url()  { sed -n 's#.*baseURL: *\(https\?://[^ ]*\)/v1.*#\1#p' "$1" | head -1; }
field_port() { sed -n 's#.*baseURL: *https\?://[^:/]*:\([0-9]\+\)/v1.*#\1#p' "$1" | head -1; }
field_id()   { sed -n 's/^ *- id: *//p' "$1" | head -1; }

is_local() {
    case $HARNESS_HOST in
        local|localhost|"$(hostname)"|"$(hostname -s)") return 0 ;;
    esac
    return 1
}

remote() { ssh -o BatchMode=yes "$HARNESS_HOST" "$@"; }

# The endpoint to WRITE into the live file. Local: the recipe's own loopback
# URL. Remote: HARNESS_ENDPOINT if set, else the head's nordlynx address -
# odysseus's ufw allows the mesh interface and allows :8903 from the LAN to
# nobody, so the mesh is the path that needs no firewall change. README,
# "Reaching the server".
endpoint_for() {  # $1 = recipe file -> scheme://host:port, no /v1
    local port e addr
    port=$(field_port "$1")
    [[ -n $port ]] || die "$1 declares no baseURL with an explicit port"
    if is_local; then field_url "$1"; return 0; fi
    e=${HARNESS_ENDPOINT:-}
    if [[ -z $e ]]; then
        addr=$(ip -4 -o addr show nordlynx 2>/dev/null | awk 'NR==1{split($4,a,"/"); print a[1]}')
        [[ -n $addr ]] || die "HARNESS_ENDPOINT is unset and this node has no nordlynx address; set it in .env, e.g. HARNESS_ENDPOINT=http://<head>:8903"
        e=http://$addr:$port
    fi
    e=${e%/}; e=${e%/v1}
    printf '%s' "$e"
}

# The recipe with ONE line rewritten: the node's endpoint. Everything else is
# the recipe and stays as written.
render() {  # $1 = recipe file, $2 = endpoint -> stdout
    sed "s#^\( *baseURL:\).*#\1 $2/v1#" "$1"
}

# The live file, fetched to a temp when the harness is on another node, so
# list/verify do not have to care where it runs. Sets LIVE_PATH and LIVE_TMP.
LIVE_PATH=""; LIVE_TMP=""
live_copy() {
    if is_local; then LIVE_PATH=$LIVE; return 0; fi
    LIVE_TMP=$(mktemp)
    remote "cat $REMOTE_DIR/dsh-home/settings.yaml" > "$LIVE_TMP" 2>/dev/null || true
    LIVE_PATH=$LIVE_TMP
}

# What a server at $1 (scheme://host:port) says it serves, one id per line.
# Empty (and exit 0) if nothing is listening - "not running yet" is a normal
# state here: you may well be configuring the harness before you start the
# model.
served_ids() {
    curl -sf --max-time 3 "$1/v1/models" 2>/dev/null \
        | grep -o '"id" *: *"[^"]*"' | sed 's/.*: *"//; s/"$//' || true
}

verify() {  # $1 = settings file; warns, and only fails on a real contradiction
    local f=$1 url id ids
    url=$(field_url "$f"); id=$(field_id "$f")
    [[ -n $url && -n $id ]] || die "$f declares no baseURL or no model id"
    # A provider that is defined but not SELECTED leaves dsh on its shipped
    # deepseek-official default, which fails with MISSING_CREDENTIAL rather
    # than falling back to the one provider that is configured.
    grep -q '^agent-default-model:' "$f" \
        || echo "${c_yel}warn${c_off}  $f sets no agent-default-model - dsh will stay on deepseek-official" >&2
    ids=$(served_ids "$url")
    if [[ -z $ids ]]; then
        echo "${c_yel}note${c_off}  nothing answering on $url yet - start it first:"
        echo "      ws up $(basename "$f" .yaml)"
        return 0
    fi
    if grep -qxF "$id" <<<"$ids"; then
        echo "${c_grn}ok${c_off}    $url is serving \"$id\""
        return 0
    fi
    echo "${c_yel}warn${c_off}  $url is up but does NOT serve \"$id\". It serves:" >&2
    indent '        ' <<<"$ids" >&2
    echo "      fix the id in $f, or use: ./use.sh --port $(field_port "$f")" >&2
    return 0
}

cmd_list() {
    local n f active="" t
    live_copy
    if [[ -s $LIVE_PATH ]]; then
        for f in settings/*.yaml; do
            t=$(mktemp); render "$f" "$(endpoint_for "$f")" > "$t"
            cmp -s "$t" "$LIVE_PATH" && { active=$(basename "$f" .yaml); rm -f "$t"; break; }
            rm -f "$t"
        done
    fi
    printf '%s%-38s %-28s %s%s\n' "$c_bold" WORKSPACE ENDPOINT MODEL "$c_off"
    for n in $(available); do
        f="settings/$n.yaml"
        printf '%s%-38s %-28s %s%s\n' \
            "$([[ $n == "$active" ]] && printf '%s' "$c_grn")" \
            "$n" "$(field_url "$f")" "$(field_id "$f")" "$c_off"
    done
    echo
    if [[ -n $active ]]; then
        echo "active: ${c_grn}$active${c_off}"
        verify "$LIVE_PATH"
    elif [[ -s $LIVE_PATH ]]; then
        echo "active: ${c_dim}a hand-written live file (matches none of the above)${c_off}"
        verify "$LIVE_PATH"
    else
        echo "active: ${c_yel}none${c_off} - the live settings.yaml does not exist, so dsh has no provider."
        echo "        ./use.sh $DEFAULT"
    fi
    [[ -n $LIVE_TMP ]] && rm -f "$LIVE_TMP"
}

# THE WEB UI WRITES BACK INTO settings.yaml. Observed: it appends
# `ui-onboarding: welcomeNoticeVersion` after a first visit, and the Models
# page is documented to persist through the same settings service. So a switch
# is not a pure `cp` onto a file only this script owns - it drops whatever the
# UI put there. That is survivable (dsh rewrites its own preferences) but it
# should never be SILENT, so the outgoing file is kept and the lost top-level
# keys are named.
keep_outgoing() {
    [[ -f $LIVE ]] || return 0
    cp "$LIVE" "$LIVE.prev"
    local lost
    lost=$(comm -23 <(top_keys "$LIVE") <(top_keys "$1"))
    [[ -n $lost ]] || return 0
    echo "${c_dim}kept  $LIVE.prev - these top-level keys are not in the new file:${c_off}"
    indent '        ' <<<"$lost"
}

top_keys() { sed -n 's/^\([A-Za-z][A-Za-z0-9_-]*\):.*/\1/p' "$1" | sort -u; }

cmd_use() {
    local n=$1 f="settings/$1.yaml" ep t old lost
    [[ -f $f ]] || { echo "use.sh: no settings for '$n'. available:" >&2
                     available | indent '  ' >&2; exit 1; }
    ep=$(endpoint_for "$f")
    t=$(mktemp)
    render "$f" "$ep" > "$t"

    if is_local; then
        mkdir -p dsh-home
        keep_outgoing "$t"
        cp "$t" "$LIVE"
        echo "wrote $LIVE from $f (endpoint $ep)"
        verify "$LIVE"
    else
        remote "mkdir -p $REMOTE_DIR/dsh-home"
        if remote "test -f $REMOTE_DIR/dsh-home/settings.yaml"; then
            old=$(mktemp)
            remote "cat $REMOTE_DIR/dsh-home/settings.yaml" > "$old"
            remote "cp $REMOTE_DIR/dsh-home/settings.yaml $REMOTE_DIR/dsh-home/settings.yaml.prev"
            lost=$(comm -23 <(top_keys "$old") <(top_keys "$t"))
            if [[ -n $lost ]]; then
                echo "${c_dim}kept  $HARNESS_HOST:$REMOTE_DIR/dsh-home/settings.yaml.prev - these top-level keys are not in the new file:${c_off}"
                indent '        ' <<<"$lost"
            fi
            rm -f "$old"
        fi
        rsync -az "$t" "$HARNESS_HOST:$REMOTE_DIR/dsh-home/settings.yaml"
        echo "wrote $HARNESS_HOST:$REMOTE_DIR/dsh-home/settings.yaml from $f (endpoint $ep)"
        verify "$t"
    fi
    rm -f "$t"
    echo
    echo "restart the harness for it to be read:  ws down deepseek-harness && ws up deepseek-harness"
}

# Build a settings file for a server this repo ships no id for. The id comes
# from the server, never from a guess - which is the entire point.
cmd_port() {
    local host=$1 port=$2 id=${3:-} ids url t
    url="http://$host:$port"
    ids=$(served_ids "$url")
    [[ -n $ids ]] || die "nothing answering on $url/v1/models - start the server first"
    if [[ -z $id ]]; then
        id=$(head -1 <<<"$ids")
        [[ $(wc -l <<<"$ids") -eq 1 ]] || {
            echo "use.sh: $url serves more than one model - pass --id:" >&2
            indent '  ' <<<"$ids" >&2; exit 1; }
    elif ! grep -qxF "$id" <<<"$ids"; then
        echo "use.sh: $url does not serve \"$id\". It serves:" >&2
        indent '  ' <<<"$ids" >&2; exit 1
    fi
    t=$(mktemp)
    cat > "$t" <<EOF
# Generated by use.sh --port $port --host $host on $(date -Is).
# The id below was read from the RUNNING server, not guessed.
llm-pi-ai:
  providers:
    gx10:
      apiKeyEnv: LOCAL_API_KEY
      api: openai-completions
      baseURL: $url/v1
      models:
        - id: $id

# Defining a provider does not SELECT one. Without this, dsh keeps its shipped
# default of deepseek-official/deepseek-flash and asks for DEEPSEEK_API_KEY.
agent-default-model:
  provider: gx10
  model: $id
EOF
    if is_local; then
        mkdir -p dsh-home
        [[ -f $LIVE ]] && cp "$LIVE" "$LIVE.prev"
        cp "$t" "$LIVE"
        echo "wrote $LIVE  ->  $url serving \"$id\""
    else
        remote "mkdir -p $REMOTE_DIR/dsh-home"
        remote "test -f $REMOTE_DIR/dsh-home/settings.yaml && cp $REMOTE_DIR/dsh-home/settings.yaml $REMOTE_DIR/dsh-home/settings.yaml.prev || true"
        rsync -az "$t" "$HARNESS_HOST:$REMOTE_DIR/dsh-home/settings.yaml"
        echo "wrote $HARNESS_HOST:$REMOTE_DIR/dsh-home/settings.yaml  ->  $url serving \"$id\""
    fi
    rm -f "$t"
    echo
    echo "restart the harness for it to be read:  ws down deepseek-harness && ws up deepseek-harness"
}

main() {
    local port="" id="" host="127.0.0.1"
    case ${1:-} in
        "")            cmd_list; return 0 ;;
        -h|--help)     sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'; return 0 ;;
        --port)
            while [[ $# -gt 0 ]]; do
                case $1 in
                    --port) port=${2:-}; shift 2 ;;
                    --id)   id=${2:-};   shift 2 ;;
                    --host) host=${2:-}; shift 2 ;;
                    *)      die "unexpected argument '$1'" ;;
                esac
            done
            [[ $port =~ ^[0-9]+$ ]] || die "--port needs a port number"
            cmd_port "$host" "$port" "$id"; return 0 ;;
        -*)            die "unknown option '$1'. try: ./use.sh --help" ;;
        *)             cmd_use "$1"; return 0 ;;
    esac
}

# Sourced by up.sh, which needs endpoint_for/cmd_use and must NOT run main
# with its own arguments. `if`, not `&&`: under `set -e` the false test would
# be the last command of the sourced file and exit the caller.
if [[ ${BASH_SOURCE[0]} == "$0" ]]; then main "$@"; fi
